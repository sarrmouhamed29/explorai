    op.create_foreign_key('raw_artifacts_owner_id_fkey', 'raw_artifacts', 'users', ['owner_id'], ['id'])

    # Roles are cluster-wide: another database (a test one, say) may have
    # created it already. NOLOGIN: it is only reached through SET ROLE.
    op.execute(
        """
        DO $$
        BEGIN
            IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'explorai_app') THEN
                CREATE ROLE explorai_app NOLOGIN NOBYPASSRLS;
            END IF;
        END
        $$
        """
    )
    # Membership lets the connecting user (the table owner) SET ROLE to it.
    op.execute("GRANT explorai_app TO CURRENT_USER")
    op.execute(
        """
        CREATE FUNCTION app_user() RETURNS uuid
        LANGUAGE sql STABLE
        AS $$ SELECT NULLIF(current_setting('app.user_id', true), '')::uuid $$
        """
    )
